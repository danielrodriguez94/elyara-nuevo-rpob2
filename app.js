function applyLanguage() {
  document.documentElement.lang = lang;


  document.querySelectorAll("[data-t]").forEach(el => {
    const key = el.dataset.t;

    if (
      TRANSLATIONS[lang]?.[key]
      !== undefined
    ) {
      el.textContent =
        TRANSLATIONS[lang][key];
    }
  });


  document.querySelectorAll(
    "[data-service-name]"
  ).forEach(el => {
    const s =
      SERVICES[
        el.dataset.serviceName
      ];

    if (s) {
      el.textContent =
        lang === "es"
          ? s.es
          : s.en;
    }
  });


  document.querySelectorAll(
    "[data-service-desc]"
  ).forEach(el => {
    const s =
      SERVICES[
        el.dataset.serviceDesc
      ];

    if (s) {
      el.textContent =
        lang === "es"
          ? s.descEs
          : s.descEn;
    }
  });


  document.querySelectorAll(
    "[data-service-price]"
  ).forEach(el => {
    const s =
      SERVICES[
        el.dataset.servicePrice
      ];

    if (!s) {
      return;
    }


    const monthly =
      s.monthly
        ? (
            lang === "es"
              ? " / mes"
              : " / month"
          )
        : "";


    el.textContent =
      `${t("from")} $${s.from}${monthly}`;
  });


  document.querySelectorAll(
    ".card .kicker"
  ).forEach(el => {

    if (
      el.textContent
        .trim()
        .toUpperCase()
      === "DIGITAL"
    ) {
      el.textContent =
        t("digital");
    }

  });


  document.querySelectorAll(
    "[data-lang-toggle]"
  ).forEach(btn => {

    btn.textContent =
      "EN / ES";

    btn.setAttribute(
      "aria-label",

      lang === "es"
        ? "Cambiar idioma a inglés"
        : "Change language to Spanish"
    );

  });


  translateHeaderAndFooter();
  translateHome();
  translatePortfolio();
  translateAbout();
  translateContact();
  translateLogin();
  translateAccount();
  translateStripePages();
  translatePageMeta();

  updateAuthUi();
}


function configReady() {
  return Boolean(
    window.ELYARA_CONFIG
      ?.SUPABASE_URL &&

    !window.ELYARA_CONFIG
      .SUPABASE_URL
      .includes("YOUR_") &&

    window.ELYARA_CONFIG
      ?.SUPABASE_ANON_KEY &&

    !window.ELYARA_CONFIG
      .SUPABASE_ANON_KEY
      .includes("YOUR_")
  );
}


function initSupabase() {
  if (
    !window.supabase ||
    !configReady()
  ) {
    return;
  }


  supabaseClient =
    window.supabase.createClient(

      window.ELYARA_CONFIG
        .SUPABASE_URL,

      window.ELYARA_CONFIG
        .SUPABASE_ANON_KEY

    );
}


async function refreshSession() {
  if (!supabaseClient) {
    return null;
  }


  const { data } =
    await supabaseClient
      .auth
      .getSession();


  currentSession =
    data.session ||
    null;


  updateAuthUi();

  return currentSession;
}


function updateAuthUi() {
  document.querySelectorAll(
    "[data-auth-label]"
  ).forEach(el => {

    el.textContent =
      currentSession
        ? t("account")
        : t("login");


    el.setAttribute(
      "href",

      currentSession
        ? "account.html"
        : "login.html"
    );

  });


  const email =
    currentSession
      ?.user
      ?.email ||
    "";


  document.querySelectorAll(
    "[data-user-email]"
  ).forEach(el => {

    el.textContent =
      email;

  });
}


async function signInGoogle() {
  if (!supabaseClient) {
    alert(
      t("supabase_missing")
    );

    return;
  }


  const redirectTo =
    `${window.location.origin}/login.html`;


  const { error } =
    await supabaseClient
      .auth
      .signInWithOAuth({

        provider: "google",

        options: {
          redirectTo
        }

      });


  if (error) {
    alert(
      error.message
    );
  }
}


async function signOut() {
  if (!supabaseClient) {
    return;
  }


  await supabaseClient
    .auth
    .signOut();


  currentSession =
    null;


  window.location.href =
    "index.html";
}


async function startService(serviceId) {
  const service =
    SERVICES[serviceId];


  if (!service) {
    return;
  }


  if (!service.checkout) {
    const url =
      new URL(
        "contact.html",
        window.location.href
      );


    url.searchParams.set(
      "service",
      serviceId
    );


    window.location.href =
      url.toString();


    return;
  }


  await refreshSession();


  if (!currentSession) {

    sessionStorage.setItem(
      "elyaraPendingService",
      serviceId
    );


    alert(
      t("sign_in_needed")
    );


    window.location.href =
      "login.html?return=services.html";


    return;
  }


  const modal =
    document.getElementById(
      "orderModal"
    );


  if (!modal) {
    return;
  }


  const modalTitle =
    document.getElementById(
      "modalTitle"
    );


  const modalText =
    document.getElementById(
      "modalText"
    );


  const modalAmount =
    document.getElementById(
      "modalAmount"
    );


  const pay =
    document.getElementById(
      "payDepositBtn"
    );


  if (modalTitle) {

    modalTitle.textContent =
      lang === "es"
        ? service.es
        : service.en;

  }


  if (modalText) {

    modalText.textContent =
      t("deposit_explain");

  }


  if (modalAmount) {

    modalAmount.textContent =
      `${t("from")} $${(
        service.from * 0.5
      ).toFixed(2)} ${
        lang === "es"
          ? "de anticipo"
          : "deposit"
      }`;

  }


  if (pay) {

    pay.dataset.serviceId =
      serviceId;


    pay.textContent =
      t("pay_deposit");

  }


  modal.style.display =
    "grid";
}


async function createCheckout(serviceId) {
  if (!currentSession) {
    await refreshSession();
  }


  if (!currentSession) {

    alert(
      t("sign_in_needed")
    );

    return;

  }


  const btn =
    document.getElementById(
      "payDepositBtn"
    );


  if (btn) {

    btn.disabled =
      true;


    btn.textContent =
      t("opening_checkout");

  }


  try {

    const res =
      await fetch(
        "/api/create-checkout",
        {

          method: "POST",

          headers: {
            "content-type":
              "application/json",

            authorization:
              `Bearer ${currentSession.access_token}`
          },

          body:
            JSON.stringify({
              serviceId
            })

        }
      );


    const data =
      await res.json();


    if (!res.ok) {

      throw new Error(
        data.error ||
        "Checkout error"
      );

    }


    window.location.href =
      data.url;


  } catch (err) {

    alert(
      err.message
    );


    if (btn) {

      btn.disabled =
        false;


      btn.textContent =
        t("pay_deposit");

    }

  }
}


async function submitContact(form) {

  const payload =
    Object.fromEntries(
      new FormData(form)
        .entries()
    );


  if (!supabaseClient) {

    alert(
      t("supabase_missing")
    );

    return;

  }


  const { error } =
    await supabaseClient
      .from(
        "contact_requests"
      )
      .insert({

        user_id:
          currentSession
            ?.user
            ?.id ||
          null,

        first_name:
          payload.first_name ||
          "",

        last_name:
          payload.last_name ||
          "",

        email:
          payload.email ||
          "",

        service:
          payload.service ||
          "",

        message:
          payload.message ||
          "",

        language:
          lang

      });


  if (error) {

    alert(
      error.message
    );

    return;

  }


  form.reset();

  applyLanguage();


  alert(
    t("request_received")
  );
}


async function loadAccount() {

  const account =
    document.querySelector(
      "[data-account-page]"
    );


  if (
    !account ||
    !supabaseClient
  ) {

    return;

  }


  await refreshSession();


  if (!currentSession) {

    account.innerHTML = `
      <section class="login-shell">

        <div class="login-card">

          <h1 class="serif">
            ${t("signed_out")}
          </h1>

          <a
            class="btn btn--navy"
            href="login.html"
          >
            ${t("login")}
          </a>

        </div>

      </section>
    `;


    return;
  }


  const user =
    currentSession.user;


  const emailEl =
    document.querySelector(
      "[data-account-email]"
    );


  if (emailEl) {

    emailEl.textContent =
      user.email ||
      "";

  }


  const { data: orders } =
    await supabaseClient
      .from("orders")
      .select(
        "service_id,service_name,amount_cents,status,created_at"
      )
      .eq(
        "user_id",
        user.id
      )
      .order(
        "created_at",
        {
          ascending:false
        }
      );


  const { data: requests } =
    await supabaseClient
      .from(
        "contact_requests"
      )
      .select(
        "service,message,status,created_at"
      )
      .eq(
        "user_id",
        user.id
      )
      .order(
        "created_at",
        {
          ascending:false
        }
      );


  const ordersBox =
    document.querySelector(
      "[data-orders]"
    );


  const requestsBox =
    document.querySelector(
      "[data-requests]"
    );


  if (ordersBox) {

    ordersBox.innerHTML =
      orders?.length

        ? orders
            .map(
              order => `

                <div class="account-row">

                  <b>
                    ${
                      order.service_name ||
                      order.service_id
                    }
                  </b>

                  <span>
                    $${(
                      (
                        order.amount_cents ||
                        0
                      ) /
                      100
                    ).toFixed(2)}
                    ·
                    ${order.status}
                  </span>

                </div>

              `
            )
            .join("")

        : `<p>${t("no_orders")}</p>`;

  }


  if (requestsBox) {

    requestsBox.innerHTML =
      requests?.length

        ? requests
            .map(
              request => `

                <div class="account-row">

                  <b>
                    ${
                      request.service ||
                      "General"
                    }
                  </b>

                  <span>
                    ${
                      request.status ||
                      "new"
                    }
                  </span>

                </div>

              `
            )
            .join("")

        : `<p>${t("no_requests")}</p>`;

  }
}


document.addEventListener(
  "DOMContentLoaded",
  async () => {

    initSupabase();


    if (supabaseClient) {

      await refreshSession();


      supabaseClient
        .auth
        .onAuthStateChange(
          (
            _event,
            session
          ) => {

            currentSession =
              session;


            updateAuthUi();

          }
        );

    }


    applyLanguage();


    document.querySelectorAll(
      "[data-lang-toggle]"
    ).forEach(btn => {

      btn.addEventListener(
        "click",
        () => {

          lang =
            lang === "en"
              ? "es"
              : "en";


          localStorage.setItem(
            "elyaraLang",
            lang
          );


          applyLanguage();

        }
      );

    });


    document.querySelectorAll(
      "[data-menu]"
    ).forEach(btn => {

      btn.addEventListener(
        "click",
        () => {

          document
            .querySelector(
              "[data-mobile]"
            )
            ?.classList
            .toggle("open");

        }
      );

    });


    const observer =
      new IntersectionObserver(

        entries => {

          entries.forEach(
            entry => {

              if (
                entry.isIntersecting
              ) {

                entry
                  .target
                  .classList
                  .add("visible");

              }

            }
          );

        },

        {
          threshold:0.12
        }

      );


    document.querySelectorAll(
      ".reveal"
    ).forEach(
      el =>
        observer.observe(el)
    );


    document.querySelectorAll(
      "[data-google-login]"
    ).forEach(btn => {

      btn.addEventListener(
        "click",
        signInGoogle
      );

    });


    document.querySelectorAll(
      "[data-signout]"
    ).forEach(btn => {

      btn.addEventListener(
        "click",
        signOut
      );

    });


    document.querySelectorAll(
      "[data-service-start]"
    ).forEach(btn => {

      btn.addEventListener(
        "click",
        () =>
          startService(
            btn.dataset
              .serviceStart
          )
      );

    });


    document.querySelectorAll(
      "[data-close]"
    ).forEach(btn => {

      btn.addEventListener(
        "click",
        () => {

          const modal =
            document.getElementById(
              "orderModal"
            );


          if (modal) {

            modal.style.display =
              "none";

          }

        }
      );

    });


    document
      .getElementById(
        "payDepositBtn"
      )
      ?.addEventListener(
        "click",
        event => {

          createCheckout(
            event
              .currentTarget
              .dataset
              .serviceId
          );

        }
      );


    const contactForm =
      document.querySelector(
        "[data-contact-form]"
      );


    if (contactForm) {

      contactForm
        .addEventListener(
          "submit",
          event => {

            event.preventDefault();

            submitContact(
              contactForm
            );

          }
        );

    }


    const params =
      new URLSearchParams(
        location.search
      );


    const serviceParam =
      params.get(
        "service"
      );


    if (
      serviceParam &&
      SERVICES[serviceParam]
    ) {

      const select =
        document.querySelector(
          'select[name="service"]'
        );


      if (select) {

        select.value =
          serviceParam;

      }

    }


    await loadAccount();

  }
);
